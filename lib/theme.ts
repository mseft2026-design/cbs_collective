export function themeToCssVariables(theme: SiteTheme): Record<string, string> {
  const { colors, layout } = theme;
  return {
    "--site-bg": colors.bg,
    "--site-bg-alt": colors.bgAlt,
    "--site-surface": colors.surface,
    "--site-surface-hover": colors.surfaceHover,
    "--site-border": colors.border,
    "--site-text": colors.text,
    "--site-text-muted": colors.textMuted,
    "--site-accent": colors.accent,
    "--site-accent-hover": colors.accentHover,
    "--site-secondary-accent": colors.secondaryAccent,
    "--site-btn-primary-bg": colors.btnPrimaryBg,
    "--site-btn-primary-text": colors.btnPrimaryText,
    "--site-btn-secondary-border": colors.btnSecondaryBorder,
    "--site-btn-secondary-text": colors.btnSecondaryText,
    "--site-content-width": layout.contentWidth,
    "--site-card-radius": layout.cardRadius,
  };
}

export function themeToCssString(theme: SiteTheme): string {
  const vars = themeToCssVariables(theme);
  return Object.entries(vars)
    .map(([key, val]) => `${key}: ${val};`)
    .join(" ");
}
